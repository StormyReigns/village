// Turns the starter Pages in src/data/pages into supabase/seed-app.sql: each game's Pages
// and Blocks, and the starter entries with their first Stable revision.
// Usage: npm run db:seed-app   (then run the SQL in Supabase's SQL Editor)
//
// Safe to run again: Pages and Blocks are updated in place, and entries that already
// exist are left alone, so community edits are never overwritten.

import { writeFileSync } from 'node:fs';
import { PAGES as FORTUNES_WEAVE } from '../src/data/pages/fortunes-weave.ts';
import { PAGES as OCARINA } from '../src/data/pages/ocarina-of-time.ts';
import type { Page } from '../src/data/pages/types.ts';

const GAMES: Record<string, Page[]> = { 'fortunes-weave': FORTUNES_WEAVE, 'ocarina-of-time': OCARINA };

const q = (v: string | undefined | null) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (v: string[] | undefined) => `array[${(v ?? []).map(q).join(', ')}]::text[]`;

const out: string[] = [
  '-- Generated by scripts/build-seed.ts from src/data/pages. Do not edit by hand.',
  '-- The game app: Pages, Blocks and starter entries. Safe to run again.',
  '',
];

for (const [game, pages] of Object.entries(GAMES)) {
  out.push(`-- ${game}`);
  out.push('insert into public.app_pages (game_id, page_key, title, short, icon, tint, blurb, position) values');
  out.push(pages.map((p, i) => `  (${q(game)}, ${q(p.id)}, ${q(p.title)}, ${q(p.short)}, ${q(p.icon)}, ${q(p.tint)}, ${q(p.blurb)}, ${i})`).join(',\n'));
  out.push('on conflict (game_id, page_key) do update set title = excluded.title, short = excluded.short, icon = excluded.icon,');
  out.push('  tint = excluded.tint, blurb = excluded.blurb, position = excluded.position;');
  out.push('');

  const blocks = pages.flatMap((p) => p.blocks.map((b) => ({ p, b })));
  out.push('insert into public.game_blocks (game_id, block_key, title, position, page_key, type, look, icon, intro, filters, by_route, stat_name, stats, symbols) values');
  out.push(blocks.map(({ p, b }, i) =>
    `  (${q(game)}, ${q(b.id)}, ${q(b.title)}, ${i}, ${q(p.id)}, ${q(b.type)}, ${q(b.look)}, ${q(b.icon)}, ${q(b.intro)}, ${arr(b.filters)}, ${b.byRoute ? 'true' : 'false'}, ${q(b.statName)}, ${b.stats ? `${q(JSON.stringify(b.stats))}::jsonb` : 'null'}, ${b.symbols ? `${q(JSON.stringify(b.symbols))}::jsonb` : 'null'})`,
  ).join(',\n'));
  out.push('on conflict (game_id, block_key) do update set title = excluded.title, position = excluded.position,');
  out.push('  page_key = excluded.page_key, type = excluded.type, look = excluded.look, icon = excluded.icon, intro = excluded.intro,');
  out.push('  filters = excluded.filters, by_route = excluded.by_route, stat_name = excluded.stat_name, stats = excluded.stats, symbols = excluded.symbols;');
  out.push('');

  const entries = blocks.flatMap(({ b }) => b.entries.map((e, i) => {
    const { id, ...content } = e;
    return { block: b.id, slug: id, position: i, content };
  }));
  if (entries.length) {
    const json = JSON.stringify(entries);
    if (json.includes('$seed$')) throw new Error('Entry text contains the SQL quote marker $seed$');
    out.push(`-- ${entries.length} starter entries, each with a first revision on Stable`);
    out.push('do $$');
    out.push('declare e jsonb; cid uuid; rid bigint;');
    out.push('begin');
    out.push(`  for e in select * from jsonb_array_elements($seed$${json}$seed$::jsonb) loop`);
    out.push('    cid := null;');
    out.push(`    insert into public.cards (game_id, block_key, slug, position)`);
    out.push(`    values (${q(game)}, e->>'block', e->>'slug', (e->>'position')::int)`);
    out.push('    on conflict (game_id, block_key, slug) do nothing returning id into cid;');
    out.push('    continue when cid is null;  -- already there: leave the community\'s edits alone');
    out.push("    insert into public.card_revisions (card_id, content, summary) values (cid, e->'content', 'Starter content') returning id into rid;");
    out.push("    insert into public.card_pointers (card_id, channel, revision_id) values (cid, 'stable', rid);");
    out.push('  end loop;');
    out.push('end $$;');
    out.push('');
  }
}

// Blocks from the old layout that the new Pages replaced.
out.push('-- Old blocks the Pages replaced');
out.push(`delete from public.game_blocks where page_key is null;`);
out.push('');

writeFileSync(new URL('../supabase/seed-app.sql', import.meta.url), out.join('\n'));
console.log(`Wrote supabase/seed-app.sql (${Object.values(GAMES).flat().length} pages)`);
