// Writes supabase/migrations/20261114000000_classes_block.sql from the starter class data, so the
// migration's new content for the 12 class cards already live matches what seed-app.sql adds for
// the rest (docs/blocks/classes.md). Usage: node scripts/build-classes-migration.ts

import { writeFileSync } from 'node:fs';
import { CARDS } from '../src/data/content/fortunes-weave.ts';
import type { Card } from '../src/data/content/types.ts';
import { classEntries } from '../src/data/pages/fortunes-weave-classes.ts';

/** The class cards already in the database before the Classes Block: the four tier summaries
 *  (now the tiers' header cards) and the eight secret classes. */
const LIVE = ['beginner-classes', 'specialty-classes', 'advanced-classes', 'master-classes', 'dancer', 'ranger', 'troubadour', 'caladrius', 'dragoon', 'guardian', 'cataphract', 'blacksmith'];

// The starter content those cards were seeded with: the old classes() from
// src/data/pages/fortunes-weave.ts (before 2026-11-11), so the migration only touches a card whose
// Stable content is still exactly that, never one the community has edited.
const slug = (s: string) => s.toLowerCase().normalize('NFKD').replace(/[^\w\s-]/g, '').trim().replace(/[\s_]+/g, '-');
const sections = (...pairs: [string, string | undefined][]) =>
  pairs.filter(([, t]) => t && t.trim()).map(([label, text]) => ({ label, text: text!.trim() }));
const routesOf = (c: Card) => (c.routes && c.routes.length < 4 ? c.routes : undefined);
function oldStarter(c: Card) {
  const tier = /^(Beginner|Specialty|Advanced|Master)/.exec(c.content.name)?.[1] ?? 'Secret';
  return {
    slug: slug(c.content.name),
    content: JSON.parse(JSON.stringify({
      name: c.content.name, routes: routesOf(c), spoiler: c.spoiler, flag: c.flag, source: c.source,
      description: c.content.why,
      sections: sections([tier === 'Secret' ? 'Where' : 'Requires', c.content.for], [tier === 'Secret' ? 'Path' : 'Classes', c.content.path]),
      categories: { Tier: tier },
    })),
  };
}
const starters = Object.fromEntries(CARDS.filter((c) => c.block === 'builds').map(oldStarter).map((s) => [s.slug, s.content]));

const rows: { slug: string; starter: unknown; content: unknown }[] = [];
for (const e of classEntries()) {
  if (!LIVE.includes(e.id)) continue;
  const { id, ...content } = e;
  if (!starters[id]) throw new Error(`No starter content for ${id}`);
  rows.push({ slug: id, starter: starters[id], content });
}
const json = JSON.stringify(rows);
if (json.includes('$c$')) throw new Error('Class text contains the SQL quote marker $c$');
if (rows.length !== LIVE.length) throw new Error('A live class card is missing from the starter data');

const sql = `-- The Classes Block (docs/blocks/classes.md): Fortune's Weave's Classes become a Block type of
-- their own, "classes" (Matt, 2026-11-11): the game's ladder of tiers with one entry per class (58),
-- each tier headed by its own card saying what the tier takes.
-- Generated by scripts/build-classes-migration.ts from src/data/pages/fortunes-weave-classes.ts.
--
-- RUN THIS, THEN supabase/seed-app.sql. The seed sets the Block's type to 'classes', which this
-- allows; run the seed first and it stops at that line with nothing changed, so just run this and
-- then the seed again. The seed adds the other 50 classes and the Divine tier's card (it never
-- overwrites a card that's already there), so they land whichever order things end up in.
--
--   * game_blocks.type may be 'classes'.
--   * The 12 class cards there today get their new content: the four tier summaries ("Beginner
--     classes"...) become the tiers' header cards (content.header = true), keeping their ids, and
--     the eight secret classes get their tier, exam ranks, unlock, skills and growth modifiers.
--     Revisions are append-only, so each gets a new revision on Stable.
--   * Only a card whose Stable content is still exactly its starter content is changed, so nothing
--     the community wrote is overwritten, and running this twice changes nothing the second time.
--   * A card with an open Draft (checking, open, approved or preview) is skipped: shipping that
--     Draft would replace the new content with the old. It's listed below for a moderator.
--
-- Safe to run twice.

alter table public.game_blocks drop constraint if exists game_blocks_type_check;
alter table public.game_blocks add constraint game_blocks_type_check
  check (type in ('collection', 'guide', 'checklist', 'timeline', 'characters', 'items', 'tierlist', 'classes'));

do $$
declare r jsonb; c record; rid bigint;
begin
  for r in select * from jsonb_array_elements($c$${json}$c$::jsonb) loop
    select k.id, v.content into c
    from public.cards k
    join public.card_pointers p on p.card_id = k.id and p.channel = 'stable'
    join public.card_revisions v on v.id = p.revision_id
    where k.game_id = 'fortunes-weave' and k.block_key = 'classes' and k.slug = r->>'slug';
    -- Matched by the card's slug, its fixed key. A card the community has edited keeps its words.
    continue when c.id is null or c.content <> (r->'starter');
    if exists (select 1 from public.drafts d where d.card_id = c.id and d.status in ('checking', 'open', 'approved', 'preview')) then
      raise notice 'Skipped % : it has an open Draft', r->>'slug';
      continue;
    end if;
    insert into public.card_revisions (card_id, content, summary)
    values (c.id, r->'content', 'Classes Block: tier, exam ranks, skills and growth modifiers')
    returning id into rid;
    update public.card_pointers set revision_id = rid, updated_at = now() where card_id = c.id and channel = 'stable';
  end loop;
end $$;

-- Class cards skipped for an open Draft (expected: none). A moderator decides each by hand.
select k.slug, d.id as draft, d.status
from public.drafts d join public.cards k on k.id = d.card_id
where k.game_id = 'fortunes-weave' and k.block_key = 'classes' and d.status in ('checking', 'open', 'approved', 'preview');

-- What the 12 cards that were there say now: "Classes Block: ..." for each one changed (expected: all
-- 12, the four headers with header = true).
select k.slug, v.summary, v.content->'categories'->>'Tier' as tier, (v.content->>'header')::boolean as header
from public.cards k
join public.card_pointers p on p.card_id = k.id and p.channel = 'stable'
join public.card_revisions v on v.id = p.revision_id
where k.game_id = 'fortunes-weave' and k.block_key = 'classes' order by k.position;
`;

writeFileSync(new URL('../supabase/migrations/20261114000000_classes_block.sql', import.meta.url), sql);
console.log('Wrote supabase/migrations/20261114000000_classes_block.sql');
